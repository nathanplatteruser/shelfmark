import type { CatalogBook } from "@/lib/types";

function book(
  isbn13: string,
  isbn10: string,
  title: string,
  author: string,
  publisher: string,
  publishedYear: string,
  pages: number,
  format: CatalogBook["format"],
  subjects: string,
): CatalogBook {
  return {
    isbn13,
    isbn10,
    title,
    author,
    publisher,
    publishedYear,
    pages,
    format,
    language: "English",
    coverUrl: `https://covers.openlibrary.org/b/isbn/${isbn13}-L.jpg`,
    subjects,
    source: "Desk catalog",
  };
}

